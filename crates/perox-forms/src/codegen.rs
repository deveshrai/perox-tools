//! Rust code for a form: a typed wrapper around `perox_ui::Form` and a trait with one
//! method per handler named in the form.
//!
//! For `Window main_window { … Button count { on clicked: count_clicked } }` you get:
//!
//! ```text
//! pub const SOURCE: &str = include_str!("…/main_window.pxui");
//! pub struct MainWindow<'a> { pub form: &'a mut perox_ui::Form }
//! impl MainWindow<'_> { pub fn count(&mut self) -> perox_ui::Widget<'_> { … } }
//! pub trait MainWindowHandlers { fn count_clicked(&mut self, ui: &mut MainWindow<'_>) {} }
//! impl MainWindow<'_> { pub fn run(handlers) … pub fn dispatch(…) … }
//! ```

use std::fmt::Write;

use crate::syntax::{Element, File};

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern",
    "false", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut",
    "pub", "ref", "return", "self", "Self", "static", "struct", "super", "trait", "true", "type",
    "unsafe", "use", "where", "while", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "try", "typeof", "unsized", "virtual", "yield",
];

/// Methods the generated `impl` already has.
const RESERVED: &[&str] = &["form", "run", "dispatch", "widget"];

/// `main_window` → `MainWindow`.
pub fn type_name(name: &str) -> String {
    name.split(['_', '-', ' '])
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut c = p.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

/// A Rust method name for a widget id.
fn method_name(id: &str) -> String {
    if RESERVED.contains(&id) {
        format!("{id}_widget")
    } else if KEYWORDS.contains(&id) {
        format!("r#{id}")
    } else {
        id.to_owned()
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodegenError(pub String);

impl std::fmt::Display for CodegenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for CodegenError {}

/// The form's struct name: from the root element's id, else `fallback` (the file stem).
pub fn form_name(file: &File, fallback: &str) -> String {
    let base = file
        .root()
        .and_then(|r| r.id.clone())
        .unwrap_or_else(|| fallback.to_owned());
    type_name(&base)
}

/// Generate the module body for a form. `source_expr` is the Rust expression for the
/// `.pxui` text, normally `include_str!("/abs/path/form.pxui")`.
pub fn generate(
    file: &File,
    source_expr: &str,
    fallback_name: &str,
) -> Result<String, CodegenError> {
    if let Some(e) = file.errors.first() {
        return Err(CodegenError(format!("form has errors: {}", e.message)));
    }
    let root = file
        .root()
        .ok_or_else(|| CodegenError("form is empty".into()))?;
    let name = form_name(file, fallback_name);
    if name.is_empty() || !name.starts_with(|c: char| c.is_ascii_alphabetic()) {
        return Err(CodegenError(format!("`{name}` isn't a usable form name")));
    }

    // Named widgets and handlers, in source order.
    let mut widgets: Vec<&Element> = Vec::new();
    let mut handlers: Vec<(String, String, String)> = Vec::new(); // method, widget, event
    let mut problems = Vec::new();
    root.walk(&mut Vec::new(), &mut |el, _| {
        if let Some(id) = &el.id {
            if widgets.iter().any(|w| w.id.as_ref() == Some(id)) {
                problems.push(format!("two widgets are named `{id}`"));
            } else {
                widgets.push(el);
            }
        }
        for h in &el.handlers {
            if KEYWORDS.contains(&h.method.as_str()) || RESERVED.contains(&h.method.as_str()) {
                problems.push(format!("`{}` can't be a handler name", h.method));
            }
            if !handlers.iter().any(|(m, _, _)| *m == h.method) {
                let who = el.id.clone().unwrap_or_else(|| el.kind.clone());
                handlers.push((h.method.clone(), who, h.event.clone()));
            }
        }
    });
    if let Some(p) = problems.into_iter().next() {
        return Err(CodegenError(p));
    }

    let mut out = String::new();
    let w = &mut out;
    let _ = writeln!(
        w,
        "// Generated by perox-forms from the `{fallback_name}` form. Do not edit."
    );
    let _ = writeln!(
        w,
        "// Change the .pxui file (or use the designer) instead.\n"
    );
    let _ = writeln!(w, "/// The form's `.pxui` source.");
    let _ = writeln!(w, "pub const SOURCE: &str = {source_expr};\n");

    let _ = writeln!(w, "/// Typed access to the widgets of `{name}`.");
    let _ = writeln!(
        w,
        "pub struct {name}<'a> {{\n    pub form: &'a mut ::perox_ui::Form,\n}}\n"
    );
    let _ = writeln!(w, "#[allow(dead_code)]");
    let _ = writeln!(w, "impl {name}<'_> {{");
    for el in &widgets {
        let id = el.id.as_deref().unwrap_or_default();
        let _ = writeln!(w, "    /// `{} {id}`", el.kind);
        let _ = writeln!(
            w,
            "    pub fn {}(&mut self) -> ::perox_ui::Widget<'_> {{\n        self.form.widget({id:?})\n    }}\n",
            method_name(id)
        );
    }
    let _ = writeln!(w, "    /// Any widget by id.");
    let _ = writeln!(
        w,
        "    pub fn widget(&mut self, id: &str) -> ::perox_ui::Widget<'_> {{\n        self.form.widget(id)\n    }}\n"
    );
    let _ = writeln!(
        w,
        "    /// Call the handler for `event`, if the form names one."
    );
    let _ = writeln!(
        w,
        "    pub fn dispatch<H: {name}Handlers + ?Sized>(handlers: &mut H, form: &mut ::perox_ui::Form, event: &::perox_ui::FormEvent) {{"
    );
    if handlers.is_empty() {
        let _ = writeln!(w, "        let _ = (handlers, form, event);");
    } else {
        let _ = writeln!(w, "        let mut ui = {name} {{ form }};");
        let _ = writeln!(w, "        match event.handler.as_deref() {{");
        for (method, _, _) in &handlers {
            let _ = writeln!(
                w,
                "            Some({method:?}) => handlers.{method}(&mut ui),"
            );
        }
        let _ = writeln!(w, "            _ => {{}}\n        }}");
    }
    let _ = writeln!(w, "    }}\n");
    let _ = writeln!(w, "    /// Open the window and run until it closes.");
    let _ = writeln!(
        w,
        "    pub fn run<H: {name}Handlers + 'static>(mut handlers: H) -> ::perox_ui::eframe::Result {{"
    );
    let _ = writeln!(
        w,
        "        ::perox_ui::run(SOURCE, move |form, event| Self::dispatch(&mut handlers, form, event))\n    }}"
    );
    let _ = writeln!(w, "}}\n");

    let _ = writeln!(
        w,
        "/// Event handlers for `{name}`. Implement the ones you need."
    );
    let _ = writeln!(w, "#[allow(unused_variables)]");
    let _ = writeln!(w, "pub trait {name}Handlers {{");
    for (method, who, event) in &handlers {
        let _ = writeln!(w, "    /// `{who}` {event}");
        let _ = writeln!(w, "    fn {method}(&mut self, ui: &mut {name}<'_>) {{}}");
    }
    let _ = writeln!(w, "}}");
    Ok(out)
}

/// For `build.rs`: compile forms into `OUT_DIR`, to include with
/// `perox_ui::include_form!("main_window")`.
pub mod build {
    use std::path::Path;

    /// Generate `OUT_DIR/<stem>_ui.rs` for one `.pxui` file. Panics with the form's
    /// errors (which is how a build script reports them).
    pub fn compile(path: impl AsRef<Path>) {
        let path = path.as_ref();
        println!("cargo:rerun-if-changed={}", path.display());
        let abs = std::fs::canonicalize(path)
            .unwrap_or_else(|e| panic!("can't read {}: {e}", path.display()));
        let src = std::fs::read_to_string(&abs)
            .unwrap_or_else(|e| panic!("can't read {}: {e}", path.display()));
        let stem = abs
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or("form")
            .to_owned();
        let file = crate::parse(&src);
        for e in &file.errors {
            let (line, col) = line_col(&src, e.span.start);
            println!(
                "cargo:warning={}:{line}:{col}: {}",
                path.display(),
                e.message
            );
        }
        let expr = format!("include_str!({:?})", abs.display().to_string());
        let code = super::generate(&file, &expr, &stem)
            .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let out = std::env::var_os("OUT_DIR").expect("OUT_DIR is set by cargo for build scripts");
        let dest = Path::new(&out).join(format!("{stem}_ui.rs"));
        std::fs::write(&dest, code)
            .unwrap_or_else(|e| panic!("can't write {}: {e}", dest.display()));
    }

    /// Compile every `.pxui` file in a directory (not recursive).
    pub fn compile_dir(dir: impl AsRef<Path>) {
        let dir = dir.as_ref();
        println!("cargo:rerun-if-changed={}", dir.display());
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        let mut files: Vec<_> = entries
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|x| x == "pxui"))
            .collect();
        files.sort();
        for f in files {
            compile(f);
        }
    }

    fn line_col(src: &str, offset: usize) -> (usize, usize) {
        let before = &src[..offset.min(src.len())];
        let line = before.matches('\n').count() + 1;
        let col = before.len() - before.rfind('\n').map_or(0, |i| i + 1) + 1;
        (line, col)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse;

    #[test]
    fn names() {
        assert_eq!(type_name("main_window"), "MainWindow");
        assert_eq!(type_name("about-dialog"), "AboutDialog");
        assert_eq!(method_name("type"), "r#type");
        assert_eq!(method_name("run"), "run_widget");
    }

    #[test]
    fn generates_accessors_and_handlers() {
        let f = parse(
            "Window main_window {\n VBox {\n Button count { text: \"Go\"; on clicked: count_clicked }\n TextEdit type { on submitted: count_clicked; on changed: typed }\n Label {}\n }\n}",
        );
        let code = generate(&f, "\"\"", "main_window").unwrap();
        assert!(code.contains("pub struct MainWindow<'a>"), "{code}");
        assert!(code.contains("pub fn count(&mut self)"), "{code}");
        assert!(code.contains("pub fn r#type(&mut self)"), "{code}");
        assert!(code.contains("fn count_clicked(&mut self, ui: &mut MainWindow<'_>) {}"));
        assert!(code.contains("fn typed(&mut self"));
        // One trait method per handler name, even when two events share it.
        assert_eq!(code.matches("fn count_clicked").count(), 1);
        assert!(code.contains("Some(\"typed\") => handlers.typed(&mut ui),"));
    }

    #[test]
    fn rejects_duplicate_ids_and_errors() {
        let f = parse("Window w { Label a {}\n Label a {} }");
        assert!(
            generate(&f, "\"\"", "w")
                .unwrap_err()
                .0
                .contains("two widgets")
        );
        let f = parse("Window w { Label a { text: } }");
        assert!(generate(&f, "\"\"", "w").is_err());
        let f = parse("Window w { Button b { on clicked: run } }");
        assert!(generate(&f, "\"\"", "w").is_err());
    }
}
